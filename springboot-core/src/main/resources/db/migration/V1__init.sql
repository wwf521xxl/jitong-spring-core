-- 计件通 Spring Boot 核心模块 · 初始表结构
-- 方言：H2 (MODE=PostgreSQL) / PostgreSQL
-- 命名保持 snake_case，接口层再转换为前端使用的 camelCase。

CREATE TABLE employees (
    id               VARCHAR(32) PRIMARY KEY,
    employee_no      INTEGER NOT NULL,
    name             VARCHAR(40) NOT NULL,
    role             VARCHAR(60) NOT NULL,
    avatar           VARCHAR(8),
    is_admin         BOOLEAN NOT NULL DEFAULT FALSE,
    can_create_job   BOOLEAN NOT NULL DEFAULT FALSE,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    pin_hash         VARCHAR(255) NOT NULL,
    token_version    INTEGER NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_employees_no UNIQUE (employee_no)
);

CREATE TABLE employee_skills (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  VARCHAR(32) NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    line         VARCHAR(20) NOT NULL,
    step_no      INTEGER NOT NULL,
    CONSTRAINT uk_employee_skills UNIQUE (employee_id, line, step_no)
);

CREATE TABLE employee_process_skills (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   VARCHAR(32) NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    process_name  VARCHAR(40) NOT NULL,
    CONSTRAINT uk_employee_process_skills UNIQUE (employee_id, process_name)
);

CREATE TABLE skill_catalog (
    name          VARCHAR(40) PRIMARY KEY,
    display_name  VARCHAR(40) NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    sort          INTEGER NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE routes (
    id          VARCHAR(32) PRIMARY KEY,
    route_key   VARCHAR(20) NOT NULL,
    line        VARCHAR(20) NOT NULL,
    name        VARCHAR(60) NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    sort        INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_routes_key UNIQUE (route_key)
);

CREATE TABLE route_steps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id      VARCHAR(32) NOT NULL REFERENCES routes (id) ON DELETE CASCADE,
    step_no       INTEGER NOT NULL,
    process_name  VARCHAR(40) NOT NULL,
    CONSTRAINT uk_route_steps UNIQUE (route_id, step_no)
);

CREATE TABLE production_jobs (
    id             VARCHAR(32) PRIMARY KEY,
    order_no       VARCHAR(64) NOT NULL,
    line           VARCHAR(20) NOT NULL,
    product        VARCHAR(100),
    spec           VARCHAR(200),
    customer       VARCHAR(100),
    planned_qty    NUMERIC(12, 3) NOT NULL DEFAULT 0,
    meters         NUMERIC(12, 3),
    unit           VARCHAR(10) NOT NULL,
    due_date       VARCHAR(20),
    priority       VARCHAR(10) NOT NULL DEFAULT '正常',
    remark         VARCHAR(500),
    route_key      VARCHAR(20),
    status         VARCHAR(20) NOT NULL DEFAULT 'active',
    qr_token       VARCHAR(80) NOT NULL,
    created_by     VARCHAR(32),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_jobs_order_no UNIQUE (order_no),
    CONSTRAINT uk_jobs_qr_token UNIQUE (qr_token)
);

CREATE TABLE job_steps (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       VARCHAR(32) NOT NULL REFERENCES production_jobs (id) ON DELETE CASCADE,
    step_no      INTEGER NOT NULL,
    step_name    VARCHAR(40),
    planned_qty  NUMERIC(12, 3) NOT NULL DEFAULT 0,
    unit         VARCHAR(10) NOT NULL,
    CONSTRAINT uk_job_steps UNIQUE (job_id, step_no)
);

CREATE TABLE job_step_groups (
    id            VARCHAR(32) PRIMARY KEY,
    job_id        VARCHAR(32) NOT NULL REFERENCES production_jobs (id) ON DELETE CASCADE,
    step_no       INTEGER NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'open',
    total_qty     NUMERIC(12, 3) NOT NULL DEFAULT 0,
    unit          VARCHAR(10),
    created_by    VARCHAR(32),
    created_at    TIMESTAMP WITH TIME ZONE,
    closed_by     VARCHAR(32),
    closed_at     TIMESTAMP WITH TIME ZONE,
    close_reason  VARCHAR(200),
    version       BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_job_step_groups UNIQUE (job_id, step_no)
);

CREATE TABLE job_step_group_members (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id     VARCHAR(32) NOT NULL REFERENCES job_step_groups (id) ON DELETE CASCADE,
    employee_id  VARCHAR(32) NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    joined_at    TIMESTAMP WITH TIME ZONE,
    record_id    VARCHAR(32),
    CONSTRAINT uk_group_members UNIQUE (group_id, employee_id)
);

CREATE TABLE piece_records (
    id               VARCHAR(32) PRIMARY KEY,
    job_id           VARCHAR(32) NOT NULL REFERENCES production_jobs (id),
    step_no          INTEGER NOT NULL,
    line             VARCHAR(20) NOT NULL,
    employee_id      VARCHAR(32) NOT NULL REFERENCES employees (id),
    qty              NUMERIC(12, 3) NOT NULL,
    unit             VARCHAR(10) NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'valid',
    note             VARCHAR(500),
    idempotency_key  VARCHAR(100) NOT NULL,
    source           VARCHAR(20) NOT NULL DEFAULT 'scan',
    photo_path       VARCHAR(200),
    device_id        VARCHAR(64),
    group_id         VARCHAR(32),
    approved_by      VARCHAR(32),
    approved_at      TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_piece_idem UNIQUE (idempotency_key)
);

CREATE TABLE corrections (
    id            VARCHAR(32) PRIMARY KEY,
    record_id     VARCHAR(32) NOT NULL REFERENCES piece_records (id),
    reason        VARCHAR(64) NOT NULL,
    note          VARCHAR(500),
    status        VARCHAR(20) NOT NULL DEFAULT 'pending',
    requested_by  VARCHAR(32) NOT NULL REFERENCES employees (id),
    approved_by   VARCHAR(32),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE job_step_group_events (
    id           VARCHAR(32) PRIMARY KEY,
    group_id     VARCHAR(32) NOT NULL REFERENCES job_step_groups (id) ON DELETE CASCADE,
    from_state   VARCHAR(20) NOT NULL,
    to_state     VARCHAR(20) NOT NULL,
    action       VARCHAR(32) NOT NULL,
    actor_id     VARCHAR(32),
    reason       VARCHAR(200),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     VARCHAR(32),
    action       VARCHAR(64) NOT NULL,
    entity_type  VARCHAR(32),
    entity_id    VARCHAR(64),
    detail       VARCHAR(500),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE settings (
    setting_key    VARCHAR(64) PRIMARY KEY,
    setting_value  VARCHAR(255) NOT NULL
);

CREATE INDEX idx_piece_job_step ON piece_records (job_id, step_no, status);
CREATE INDEX idx_piece_employee_time ON piece_records (employee_id, created_at);
CREATE INDEX idx_piece_line_time ON piece_records (line, created_at);
CREATE INDEX idx_corrections_status ON corrections (status);
CREATE INDEX idx_group_events_group ON job_step_group_events (group_id, created_at);
CREATE INDEX idx_jobs_status_created ON production_jobs (status, created_at);
CREATE INDEX idx_audit_created ON audit_log (created_at);
